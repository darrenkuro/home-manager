# travel.sh — portable shell kit for machines that aren't mine.
#
#   source <(curl -fsSL tinyurl.com/darrenkuro)           # this session only
#   source <(curl -fsSL tinyurl.com/darrenkuro) install   # persist + take over the rc
#   (long form: https://raw.githubusercontent.com/darrenkuro/home-manager/main/travel.sh)
#
# One command = aliases + functions + starship + global gitignore, all
# with my real config files.
# Session mode: missing tools are fetched as static builds into a per-user
# /tmp cache (survives shells, gone on reboot, nothing written to $HOME).
# Install mode (for my own no-root workstations): tools go to ~/.local/bin,
# configs + a copy of this script to ~/.local/share/dktravel, and the
# current shell's rc (~/.zshrc or ~/.bashrc) is OVERWRITTEN with one line
# that sources that copy; the original is kept as <rc>.bak. Later shells
# start offline. travel-update refreshes, travel-uninstall restores the rc.
# Works in bash and zsh; binary fetch is Linux x86_64/aarch64 only.

_DK_RAW=https://raw.githubusercontent.com/darrenkuro/home-manager/main
_DK_HOME="$HOME/.local/share/dktravel"
_DK_MARK="# dktravel: generated by travel.sh"
if [ "${1-}" = install ] || [ -f "$_DK_HOME/travel.sh" ]; then
    _DK_DIR=$_DK_HOME
    _DK_BIN=$HOME/.local/bin
else
    _DK_DIR="/tmp/dktravel-$(id -u)"
    _DK_BIN=$_DK_DIR/bin
fi
mkdir -p "$_DK_DIR" "$_DK_BIN"

for _dk_p in "$HOME/.local/bin" "$_DK_BIN"; do
    case ":$PATH:" in
        *":$_dk_p:"*) ;;
        *) PATH="$_dk_p:$PATH" ;;
    esac
done
export PATH
unset _dk_p

# ── Record a fetched tool, so travel-uninstall removes only what it added
_dk_got() {
    echo "dk: $1 → $2"
    printf '%s\n' "$1" >> "$_DK_DIR/fetched"
}

# ── Fetch static binaries into $1, skipping tools already reachable
_dk_fetch() {
    [ "$(uname -s)" = "Linux" ] || {
        echo "dk: binary fetch is Linux-only" >&2
        return 1
    }
    local dest=$1 arch tmp spec repo pattern name url
    arch=$(uname -m) # x86_64 | aarch64
    mkdir -p "$dest"
    tmp=$(mktemp -d)

    # starship + jq publish version-less assets; grab them directly
    if ! command -v starship > /dev/null 2>&1; then
        curl -fsSL "https://github.com/starship/starship/releases/latest/download/starship-$arch-unknown-linux-musl.tar.gz" |
            tar -xzf - -C "$dest" starship && _dk_got starship "$dest"
    fi
    if ! command -v jq > /dev/null 2>&1; then
        curl -fsSL -o "$dest/jq" \
            "https://github.com/jqlang/jq/releases/latest/download/jq-linux-$([ "$arch" = x86_64 ] && echo amd64 || echo arm64)" &&
            chmod +x "$dest/jq" && _dk_got jq "$dest"
    fi

    # the rest embed versions in asset names; resolve via the GitHub API
    for spec in \
        "eza-community/eza|${arch}-unknown-linux-musl.tar.gz|eza" \
        "sharkdp/fd|${arch}-unknown-linux-musl.tar.gz|fd" \
        "sharkdp/bat|${arch}-unknown-linux-musl.tar.gz|bat" \
        "junegunn/fzf|linux_$([ "$arch" = x86_64 ] && echo amd64 || echo arm64).tar.gz|fzf"; do
        repo=${spec%%|*}
        pattern=$(printf '%s' "$spec" | cut -d'|' -f2)
        name=${spec##*|}
        command -v "$name" > /dev/null 2>&1 && continue
        url=$(curl -fsSL "https://api.github.com/repos/$repo/releases/latest" |
            grep -o "https://[^\"]*$pattern" | head -1)
        if [ -z "$url" ]; then
            echo "dk: skip $name (no asset matching $pattern)" >&2
            continue
        fi
        curl -fsSL "$url" | tar -xzf - -C "$tmp" &&
            find "$tmp" -type f -name "$name" -exec mv {} "$dest/$name" \; &&
            chmod +x "$dest/$name" && _dk_got "$name" "$dest"
    done
    /bin/rm -rf "$tmp"
}

# ── Auto-provision the bin dir: fetch whatever this box is missing, once
#    (the stamp keeps later shells offline even if a tool has no build here;
#    install / travel-update fetch again)
if [ "$(uname -s)" = "Linux" ] &&
    { [ "${1-}" = install ] || [ ! -e "$_DK_DIR/provisioned" ]; }; then
    touch "$_DK_DIR/provisioned"
    for _dk_t in starship eza fd bat fzf jq; do
        if ! command -v "$_dk_t" > /dev/null 2>&1; then
            _dk_fetch "$_DK_BIN"
            break
        fi
    done
    unset _dk_t
fi

# ── My starship config (same file my machines use via starship.nix)
if [ ! -s "$_DK_DIR/starship.toml" ]; then
    curl -fsSL "$_DK_RAW/configs/starship.toml" -o "$_DK_DIR/starship.toml" 2> /dev/null
fi
[ -s "$_DK_DIR/starship.toml" ] && export STARSHIP_CONFIG="$_DK_DIR/starship.toml"
export STARSHIP_CACHE="$_DK_DIR/cache" # keep starship's session logs out of $HOME

# ── My global gitignore (same file git.nix installs as ~/.config/git/ignore);
#    injected via env so nothing is written to ~/.gitconfig
if [ ! -s "$_DK_DIR/gitignore" ]; then
    curl -fsSL "$_DK_RAW/configs/gitignore" -o "$_DK_DIR/gitignore" 2> /dev/null
fi
if [ -s "$_DK_DIR/gitignore" ]; then
    export GIT_CONFIG_COUNT=1
    export GIT_CONFIG_KEY_0=core.excludesFile
    export GIT_CONFIG_VALUE_0="$_DK_DIR/gitignore"
fi

# ── Install mode: persist the kit and take over the current shell's rc
_dk_rc() {
    if [ -n "${ZSH_VERSION-}" ]; then
        echo "$HOME/.zshrc"
    else
        echo "$HOME/.bashrc"
    fi
}

_dk_install() {
    local rc bak
    rc=$(_dk_rc)
    if ! curl -fsSL "$_DK_RAW/travel.sh" -o "$_DK_DIR/travel.sh.new"; then
        echo "dk: could not download travel.sh, nothing installed" >&2
        return 1
    fi
    mv -f "$_DK_DIR/travel.sh.new" "$_DK_DIR/travel.sh"
    if ! grep -qF "$_DK_MARK" "$rc" 2> /dev/null; then
        if [ -e "$rc" ]; then
            bak="$rc.bak"
            [ -e "$bak" ] && bak="$rc.bak.$(date +%Y%m%d-%H%M%S)"
            printf '\033[1;31mdk: WARNING: overwriting %s (original saved as %s)\033[0m\n' \
                "$rc" "$bak" >&2
            cp -p "$rc" "$bak" || return 1
            printf '%s|%s\n' "$rc" "$bak" >> "$_DK_DIR/rc-backups"
        else
            printf '\033[1;31mdk: WARNING: creating %s\033[0m\n' "$rc" >&2
            printf '%s|\n' "$rc" >> "$_DK_DIR/rc-backups"
        fi
    fi
    cat > "$rc" << EOF
$_DK_MARK (travel-uninstall restores the original)
[ -f "\$HOME/.local/share/dktravel/travel.sh" ] && . "\$HOME/.local/share/dktravel/travel.sh"
EOF
    echo "dk: installed to ~/.local/bin + $_DK_DIR; new shells load it from $rc"
}

travel-update() {
    # shellcheck disable=SC1090
    source <(curl -fsSL "$_DK_RAW/travel.sh") install
}

travel-uninstall() {
    local line rc bak name
    # every rc the kit took over (bash and zsh): put the original back,
    # or remove the rc if the kit created it
    if [ -f "$_DK_HOME/rc-backups" ]; then
        while IFS= read -r line; do
            rc=${line%%|*}
            bak=${line#*|}
            grep -qF "$_DK_MARK" "$rc" 2> /dev/null || continue
            if [ -n "$bak" ] && [ -e "$bak" ]; then
                mv -f "$bak" "$rc" && echo "dk: restored $rc"
            else
                /bin/rm -f "$rc" && echo "dk: removed $rc"
            fi
        done < "$_DK_HOME/rc-backups"
    fi
    if [ -f "$_DK_HOME/fetched" ]; then
        while IFS= read -r name; do
            /bin/rm -f "$HOME/.local/bin/$name"
        done < "$_DK_HOME/fetched"
    fi
    /bin/rm -rf "$_DK_HOME"
    echo "dk: uninstalled; open a new shell"
}

